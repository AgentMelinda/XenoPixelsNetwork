    public static final int GEN_MIN = 1;
    public static final int GEN_MAX = 4;
    /** The generation that ships. */
    public static final int GEN_DEFAULT = 4;

    /** One animation: the name DragonMineZ knows it by, and how long it is. */
    public record Clip(String name, float seconds) {
    }

    private record Entry(Clip gen1, Clip gen2, Clip gen3, float speed) {
        Clip forGeneration(int generation) {
            return switch (generation) {
                case 2 -> gen2 != null ? gen2 : gen1;
                case 3 -> gen3 != null ? gen3 : gen1;
                default -> gen1;
            };
        }
    }

