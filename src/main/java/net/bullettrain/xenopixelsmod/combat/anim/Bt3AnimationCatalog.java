/**
 * Which DragonMineZ animation each combat beat plays, in each authored generation.
 *
 * <p><b>Common, not client.</b> This used to live inside {@code Bt3AnimationBinding} in a client
 * package, which meant the server had no way to name the clip an NPC should play. The PAL clip id
 * and the mash speed calculation stay over there; the names and lengths live here so both sides can
 * read them.
 *
 * <h2>Four generations, all shipped</h2>
 * <ul>
 *   <li><b>1</b> — exactly what shipped before v3 existed: a mix of our first clips and stock
 *       DragonMineZ ones where theirs already read better.</li>
 *   <li><b>2</b> — the {@code _v2} variants. Not really a second authoring pass: they were derived
 *       from the first by scaling the yaw down.</li>
 *   <li><b>3</b> — the {@code _v3} set, posed from scratch for Budokai Tenkaichi 3 and, crucially,
 *       authored at the length of one mash beat. Generation 1 and 2 clips are 0.40–0.72s against a
 *       0.30s beat, so the mash has to run them at up to 2.4× and the 360s smear; every v3 clip
 *       fits inside about 1.5×.</li>
 *   <li><b>4</b> — forward-centred strikes that preserve DMZ camera/crosshair aim, plus explicit
 *       full-turn spin attacks for the beats that are meant to rotate the fighter.</li>
 * </ul>
 * A generation with no variant for a beat falls back to generation 1 rather than to nothing, which
 * is why older generations may still reuse DragonMineZ clips for beats they did not author.
 *
 * <p>Clip lengths are the {@code animation_length} of the named clip. Ours come from
 * {@code assets/xenopixelsmod/animations/entity/bt3_combat.animation.json} (generated by
 * {@code tools/make_bt3_animations.py}); the DragonMineZ ones from
 * {@code assets/dragonminez/animations/entity/races/combat.animation.json} inside their jar, so a
 * DragonMineZ update that retimes a clip is something to re-read here.
 */
