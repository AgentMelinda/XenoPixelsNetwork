    private Bt3AnimationCatalog() {
    }

    /** Clamps anything to a generation this build knows. */
    public static int clampGeneration(int generation) {
        return Math.max(GEN_MIN, Math.min(GEN_MAX, generation));
    }

    /** The clip {@code intent} plays in {@code generation}, or null for an unbound intent. */
    public static Clip clipFor(Bt3AnimationIntent intent, int generation) {
        Entry entry = intent == null ? null : ENTRIES.get(intent);
        if (entry == null) {
            return null;
        }
        int clamped = clampGeneration(generation);
        if (clamped == 4) {
            return GEN4.getOrDefault(intent, entry.forGeneration(3));
        }
        return entry.forGeneration(clamped);
    }

    /** The authored playback multiplier for {@code intent}, before any beat scaling. */
    public static float speedOf(Bt3AnimationIntent intent) {
        Entry entry = intent == null ? null : ENTRIES.get(intent);
        return entry == null ? 1.0f : entry.speed();
    }

    /**
     * Every animation name this mod ships, which DragonMineZ's {@code CombatAnimationResolver} must
     * be told about or it resolves them to nothing.
     */
    public static Set<String> customAnimationNames() {
        return Collections.unmodifiableSet(CUSTOM_NAMES);
    }

    /**
     * Every name that may be played through the scripting API: ours plus the stock DragonMineZ
     * clips the table above binds. Anything outside this is rejected so a script gets an answer
     * rather than silence.
     */
    public static Set<String> playableAnimationNames() {
        Set<String> all = new LinkedHashSet<>(CUSTOM_NAMES);
        for (Bt3AnimationIntent intent : ENTRIES.keySet()) {
            for (int gen = GEN_MIN; gen <= GEN_MAX; gen++) {
                all.add(clipFor(intent, gen).name());
            }
        }
        return Collections.unmodifiableSet(all);
    }

    public static boolean isPlayable(String animation) {
        return animation != null && playableAnimationNames().contains(animation.trim());
    }

    private static Clip clip(String name, float seconds) {
        register(name);
        return new Clip(name, seconds);
    }

    private static Clip xenoClip(String suffix, float seconds) {
        return clip("combat.xeno_" + suffix, seconds);
    }

    private static void xeno(Bt3AnimationIntent intent, float speed,
                             String g1, float s1, String g2, float s2, String g3, float s3) {
        entry(intent, speed, xenoClip(g1, s1), xenoClip(g2, s2), xenoClip(g3, s3));
    }

    private static void entry(Bt3AnimationIntent intent, float speed, Clip g1, Clip g2, Clip g3) {
        ENTRIES.put(intent, new Entry(g1, g2, g3, speed));
    }

    private static void v4(Bt3AnimationIntent intent, String suffix, float seconds) {
        GEN4.put(intent, xenoClip(suffix + "_v4", seconds));
    }

    private static void register(String... names) {
        for (String name : names) {
            if (name != null && name.startsWith("combat.xeno_")) {
                CUSTOM_NAMES.add(name);
            }
        }
    }
